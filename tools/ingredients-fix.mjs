const DEPT = { "Кокосовое молоко": "can", "Лимон": "fruit", "Лайм": "fruit", "Апельсины": "fruit", "Кофе": "pantry", "Банан": "fruit", "Масло растительное": "pantry" };
// Не цельный продукт: сколько граммов покупки на грамм в рецепте
const K = { "Сок лимона": 3, "Сок лимона свежий": 3, "Лимонный сок": 3, "Лайм (сок)": 3.3, "Сок апельсина свежий": 2, "Лимонная цедра": 20 };
const SKIP = ["Вода или молоко растительное"];
const PANTRY = ["Лимонный сок и соль", "Соль и лимонный сок"];

for (const [raw, v] of Object.entries(d)) {
  if (to.has(v.n)) v.n = to.get(v.n);
  if (K[raw]) {
    v.k = K[raw];
    v.l = false;
    v.n = raw.includes("апельсин") ? "Апельсины" : raw.includes("Лайм") ? "Лайм" : "Лимон";
    v.d = "fruit";
  }
  if (v.n in UNIT) v.u = UNIT[v.n];
  if (v.n in DEPT) v.d = DEPT[v.n];
  if (SKIP.includes(raw)) v.s = "skip";
  if (PANTRY.includes(raw)) (v.d = "pantry"), (v.n = "Соль"), (v.l = false);
  if (v.d === "pantry") v.u = null;
}
// Один отдел и одна единица на каноническое имя — по большинству
const groups = {};
for (const v of Object.values(d)) (groups[v.n] ??= []).push(v);
for (const list of Object.values(groups)) {
  const cnt = {};
  for (const v of list) cnt[v.d] = (cnt[v.d] ?? 0) + 1;
  const dept = Object.entries(cnt).sort((a, b) => b[1] - a[1])[0][0];
  const unit = list.find((v) => v.u)?.u ?? null;
  const liquid = list.some((v) => v.l && !v.k);
  for (const v of list) (v.d = dept), (v.u = v.d === "pantry" ? null : unit), (v.l = liquid);
}
fs.writeFileSync("public/ingredients.json", JSON.stringify(d).replace(/},"/g, '},\n"'));
console.log("канонических имён:", Object.keys(groups).length);
