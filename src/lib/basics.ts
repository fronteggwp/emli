export type Basic = Recipe & { basic: true; meals: Meal[] };

const r1 = (n: number) => Math.round(n * 10) / 10;

export const BASICS: Basic[] = DEFS.map((d) => {
  const ingredients = d.items.map(([name, grams]) => ({ name, grams, note: null, per100: F[name] }));
  const sum = ingredients.reduce(
    (a, i) => ({
      kcal: a.kcal + (i.per100[0] * i.grams) / 100,
      protein: a.protein + (i.per100[1] * i.grams) / 100,
      fat: a.fat + (i.per100[2] * i.grams) / 100,
      carbs: a.carbs + (i.per100[3] * i.grams) / 100,
    }),
    { kcal: 0, protein: 0, fat: 0, carbs: 0 },
  );
  return {
    id: `b-${d.id}`,
    title: d.title,
    emoji: d.emoji,
    category: d.category,
    tags: ["простое", "быстро", ...(d.tags ?? [])],
    time: d.time,
    servings: 1,
    difficulty: 1,
    description: d.description,
    ingredients,
    steps: d.steps,
    tip: null,
    serving: { kcal: Math.round(sum.kcal), protein: r1(sum.protein), fat: r1(sum.fat), carbs: r1(sum.carbs), grams: ingredients.reduce((a, i) => a + i.grams, 0) },
    photo: null,
    basic: true,
    meals: d.meals,
  };
});
